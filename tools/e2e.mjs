// Doorloopt de offerteflow: maat kiezen (ook eigen maat), toevoegen, naar /offerte, formulier invullen.
import { chromium } from 'playwright';
const base = process.env.BASE || 'http://localhost:4447/';
const b = await chromium.launch({ executablePath: process.env.CHROME || '/opt/pw-browsers/chromium' });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 } });
const p = await ctx.newPage();
const fouten = [];
p.on('pageerror', (e) => fouten.push(e.message));
await p.goto(base + 'product/eettafel-viking/', { waitUntil: 'networkidle' });
await p.check('input[name="maat"][value="B200 x D100 x H78"]', { force: true });
await p.click('text=Zet in offerteaanvraag');
console.log('teller na 1:', await p.textContent('[data-offerte-teller]'));
await p.click('text=Andere maat');
await p.fill('[name="b"]', '235');
await p.fill('[name="h"]', '76');
await p.fill('[name="opmerking"]', 'Graag met 4 cm dik blad');
console.log('wa-link:', decodeURIComponent((await p.getAttribute('[data-wa]', 'href')).split('text=')[1]).replace(/\n/g, ' | '));
await p.click('text=Zet in offerteaanvraag');
console.log('teller na 2:', await p.textContent('[data-offerte-teller]'));
await p.goto(base + 'product/beaufort-bank/', { waitUntil: 'networkidle' });
await p.click('text=Andere maat');
await p.click('text=Zet in offerteaanvraag');
console.log('fout zonder maat zichtbaar:', await p.isVisible('[data-maat-fout]'));
await p.goto(base + 'offerte/', { waitUntil: 'networkidle' });
console.log('regels:', await p.locator('[data-lijst] li').count());
await p.screenshot({ path: 'shots/e2e-offerte.png', fullPage: true });
await p.click('text=Offerte aanvragen');
console.log('validatie:', await p.textContent('[data-fout]'));
await p.fill('[name="naam"]', 'Test Klant');
await p.fill('[name="email"]', 'test@example.com');
let mail = '';
p.on('framenavigated', (f) => { if (f.url().startsWith('mailto:')) mail = f.url(); });
p.on('request', (r) => { if (r.url().startsWith('mailto:')) mail = r.url(); });
await Promise.race([p.click('text=Offerte aanvragen'), p.waitForTimeout(1500)]);
await p.waitForTimeout(800);
const nu = p.url();
console.log('mailto:', (mail || nu).slice(0, 80));
console.log('paginafouten:', fouten.join(' | ') || 'geen');
await b.close();
